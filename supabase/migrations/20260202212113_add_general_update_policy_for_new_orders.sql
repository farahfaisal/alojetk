-- إضافة سياسة UPDATE للمستخدمين المسجلين
-- هذه السياسة ستسمح للـ triggers بتحديث الطلبات الجديدة
CREATE POLICY "Allow system updates on orders"
  ON orders
  FOR UPDATE
  TO public
  USING (true)
  WITH CHECK (true);
