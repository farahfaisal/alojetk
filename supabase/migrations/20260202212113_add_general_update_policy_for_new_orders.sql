  1. التغييرات
    - إضافة سياسة UPDATE للمستخدمين المسجلين لتحديث طلباتهم الخاصة
    - هذا يسمح للـ triggers بتحديث الطلبات الجديدة حتى لو كانت بحالة 'pending'

  2. الأمان
    - السياسة تسمح فقط للعملاء بتحديث طلباتهم الخاصة
    - لا تؤثر على السياسات الأخرى الموجودة
