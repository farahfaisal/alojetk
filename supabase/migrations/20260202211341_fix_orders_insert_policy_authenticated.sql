/*
  # إصلاح سياسة إدراج الطلبات للمستخدمين المسجلين

  1. التغييرات
    - إضافة سياسة INSERT للمستخدمين المسجلين (authenticated) لجدول orders
    - السماح للمستخدمين المسجلين بإنشاء طلبات جديدة

  2. الأمان
    - السياسة تسمح للمستخدمين المسجلين فقط بإنشاء طلبات
    - لا توجد قيود إضافية على البيانات المدرجة لأن النظام يتحقق من صحة البيانات في الكود
*/

-- إضافة سياسة INSERT للمستخدمين المسجلين
CREATE POLICY "Authenticated users can create orders"
  ON orders
  FOR INSERT
  TO authenticated
  WITH CHECK (true);
